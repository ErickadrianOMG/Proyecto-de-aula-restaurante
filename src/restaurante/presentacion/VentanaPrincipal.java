    private void instalarHoverNavegacion(javax.swing.JButton boton) {
        boton.setOpaque(true);
        boton.setContentAreaFilled(true);
        aplicarEstiloNavegacion(boton, false);
        boton.setFocusPainted(false);
        boton.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
        boton.putClientProperty("JButton.buttonType", "roundRect");

        boton.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseEntered(MouseEvent e) {
                aplicarEstiloNavegacion(boton, true);
            }

            @Override
            public void mouseExited(MouseEvent e) {
                aplicarEstiloNavegacion(boton, boton == botonSeccionActiva);
            }
        });
    }

    private void aplicarEstiloNavegacion(javax.swing.JButton boton, boolean resaltado) {
        if (resaltado) {
            boton.setBackground(Tema.TARJETA.brighter());
            boton.setForeground(Tema.ACENTO.brighter());
            boton.setBorderPainted(true);
            boton.setBorder(BorderFactory.createCompoundBorder(
                    BorderFactory.createLineBorder(Tema.BORDE.brighter()),
                    BorderFactory.createEmptyBorder(0, 11, 0, 11)));
        } else {
            boton.setBackground(Tema.LATERAL);
            boton.setForeground(Tema.TEXTO);
            boton.setBorderPainted(false);
            boton.setBorder(BorderFactory.createEmptyBorder(0, 12, 0, 12));
        }
    }

    private void marcarSeccionActiva(javax.swing.JButton boton) {
        if (botonSeccionActiva != null && botonSeccionActiva != boton) {
            aplicarEstiloNavegacion(botonSeccionActiva, false);
        }
        botonSeccionActiva = boton;
        aplicarEstiloNavegacion(botonSeccionActiva, true);
    }

